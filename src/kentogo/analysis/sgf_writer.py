"""Write the analysis of a game into its SGF nodes, in the same way as KaTrain saves a game.

Written for KentoGo with the same behavior as KaTrain 1.20.0's GameNode.sgf_properties and
Game.write_sgf (katrain/core/game_node.py and game.py), which are methods of KaTrain's classes
and cannot be copied unchanged. For each node:

- The user's notes stay at the top of the comment; KaTrain's old texts (marked with KaTrain's
  invisible marker) are replaced, as when KaTrain loads and saves a game.
- KaTrain's comment (see analysis.comment) is written when the node and the node before it are
  analyzed, and either the node has notes, or its player gets comments (save_comments_player)
  and the class of its loss is chosen in save_feedback (a loss of exactly 0 gets none, as in KaTrain).
- The best moves are marked (MA for the top move, SQ for moves losing 0.5 points or less) when save_marks is on.
- The analysis data (KT) is written when the node's analysis is complete; KentoGo always writes it.
- The root gets KaTrain's last comment ("SGF generated by ..."), CA, AP and KTV, and KGM[KentoGo], so that
  KentoGo knows that the losses are read in the position before each move (see analysis.played_moves).

Differences from KaTrain, kept small on purpose:
- The loss of a move in the comments is KentoGo's (see analysis.played_moves), and a score of 0 is
  written as 0. With the marks on, the start message is written once (KaTrain writes it twice).
- The program in the root's comment and AP is KentoGo, because KentoGo wrote the file.
  (KaTrain then treats the game as one it did not play, and keeps its player names.)
- The two lines of a move that KaTrain took back in a teaching game are kept: KaTrain forgets them
  when it loads and saves a game again, but KentoGo needs them to know such moves (see mistakes.extract).
- Which players get comments: KaTrain uses the players set on its screen at that time; KentoGo
  uses the player names in the game (a player that is not KaTrain's AI counts as a human).
"""

from __future__ import annotations

from dataclasses import dataclass

from pysgf import GoNode
from pysgf import Move as SgfMove

from kentogo.analysis.analysis_settings import AnalysisSettings
from kentogo.analysis.comment import CommentedMove, candidate_moves, move_comment
from kentogo.analysis.game_analysis import GameAnalysis
from kentogo.analysis.played_moves import MODE_MARK, played_move_loss
from kentogo.common.types import Move
from kentogo.record.katrain_comment import INTERNAL_MARKER, SEPARATOR, read_comment
from kentogo.record.katrain_kt import SUPPORTED_VERSION, encode_kt
from kentogo.record.katrain_texts import KATRAIN_TEXTS
from kentogo.record.players import AI, classify_katrain_name
from kentogo.vendor.katrain_analysis import evaluation_class

PROGRAM_NAME = "KentoGo"


@dataclass(frozen=True)
class WriteSettings:
    """What the comments need besides the settings of the analysis.

    Attributes:
        settings: The settings of the analysis.
        version: KentoGo's version, for the root's comment and AP.
    """

    settings: AnalysisSettings
    version: str


def write_analysis(game: GameAnalysis, write: WriteSettings) -> None:
    """Write the analysis into the properties of all nodes of the game (the nodes are changed)."""
    commented = _players_with_comments(game.root, write.settings)
    for node in game.nodes:
        if node.parent is None:
            _write_root(node, write)
            _write_kt(game, node)
        else:
            _write_node(game, node, commented, write)


def _write_node(game: GameAnalysis, node: GoNode, commented: dict[str, bool], write: WriteSettings) -> None:
    """Write KaTrain's comment, the marks and the analysis data of one node."""
    notes, info = read_comment("".join(node.get_list_property("C", [])))
    comments = []
    if _gets_comment(game, node, notes, commented, write):
        if write.settings.save_marks:
            _write_marks(game, node)
        auto_undo = info is not None and info.teaching_undo
        comments.append("\n" + _comment(game, node, auto_undo, write) + INTERNAL_MARKER)
    _write_kt(game, node)
    _set_comments(node, notes, comments)


def _gets_comment(
    game: GameAnalysis, node: GoNode, notes: str, commented: dict[str, bool], write: WriteSettings
) -> bool:
    """Tell whether KaTrain writes its comment on a node (see the module's docstring)."""
    move, settings = node.move, write.settings
    if move is None or game.analysis(node.parent) is None or game.analysis(node) is None:
        return False
    points_lost = played_move_loss(game, node)
    show_class = bool(points_lost) and settings.save_feedback[evaluation_class(points_lost, settings.eval_thresholds)]
    return bool(notes) or (commented.get(move.player, False) and show_class)


def _comment(game: GameAnalysis, node: GoNode, auto_undo: bool, write: WriteSettings) -> str:
    """Return KaTrain's comment on the move of a node."""
    move = node.move
    loss = played_move_loss(game, node)
    commented = CommentedMove(node.depth, Move(move.player, move.coords), auto_undo, loss)
    before, after = game.analysis(node.parent), game.analysis(node)
    return move_comment(commented, before, after, node.board_size, write.settings.language)


def _write_marks(game: GameAnalysis, node: GoNode) -> None:
    """Mark KataGo's top move (MA) and the moves losing 0.5 points or less (SQ) before the node, as KaTrain."""
    candidates = candidate_moves(game.analysis(node.parent), node.move.player, node.board_size)
    top = SgfMove.from_gtp(candidates[0]["move"]).sgf(node.board_size)
    good = [
        SgfMove.from_gtp(values["move"]).sgf(node.board_size)
        for values in candidates
        if values["pointsLost"] <= 0.5 and values["move"] != "pass" and values["order"] != 0
    ]
    if good and "SQ" not in node.properties:
        node.properties["SQ"] = good
    if top and "MA" not in node.properties:
        node.properties["MA"] = [top]


def _write_kt(game: GameAnalysis, node: GoNode) -> None:
    """Write the analysis data of a node when its analysis is complete, and remove old data."""
    node.properties.pop("KT", None)
    analysis = game.analysis(node)
    if analysis is not None and analysis.get("completed"):
        node.properties["KT"] = encode_kt(analysis)


def _write_root(root: GoNode, write: WriteSettings) -> None:
    """Write the root's comment, CA, AP, KTV and KGM."""
    notes, _ = read_comment("".join(root.get_list_property("C", [])))
    comments = []
    if write.settings.save_marks:
        texts = KATRAIN_TEXTS.get(write.settings.language, KATRAIN_TEXTS["en"])
        comments.append(texts["SGF start message"] + INTERNAL_MARKER + "\n")
    comments.append(f"\nSGF generated by {PROGRAM_NAME} {write.version}{INTERNAL_MARKER}\n")
    root.properties["CA"] = ["UTF-8"]
    root.properties["AP"] = [f"{PROGRAM_NAME}:{write.version}"]
    root.properties["KTV"] = [SUPPORTED_VERSION]
    root.properties["KGM"] = [MODE_MARK]
    _set_comments(root, notes, comments)


def _set_comments(node: GoNode, notes: str, comments: list[str]) -> None:
    """Put the notes at the top of the comments and write them into C, as KaTrain (or remove C)."""
    if notes:
        comments.insert(0, f"{notes}\n")
    if comments:
        node.properties["C"] = [SEPARATOR.join(comments).strip("\n")]
    else:
        node.properties.pop("C", None)


def _players_with_comments(root: GoNode, settings: AnalysisSettings) -> dict[str, bool]:
    """Return which players get comments: all when eval_show_ai is on, otherwise the humans."""
    return {
        color: settings.eval_show_ai or classify_katrain_name(str(root.get_property("P" + color, ""))) != AI
        for color in "BW"
    }
