"""Tests for kentogo.analysis.sgf_writer and saving (writing the analysis into the SGF file, in KaTrain's format)."""

from datetime import datetime

from pysgf import GoGame

from kentogo.analysis.analysis_settings import AnalysisSettings
from kentogo.analysis.analyze import DeepTargets, analyze_game
from kentogo.analysis.game_analysis import EngineValues
from kentogo.analysis.saving import back_up, backup_folder, write_game
from kentogo.analysis.sgf_writer import WriteSettings, kept_analysis, write_analysis
from kentogo.mistakes.extract import ExtractSettings, extract_problems
from kentogo.record.katrain_comment import INTERNAL_MARKER, SEPARATOR, read_comment
from kentogo.record.katrain_kt import decode_kt
from kentogo.record.kentogo_data import read_kgd, write_kgd

HUMAN = f"Human (Normal Game){INTERNAL_MARKER}"
AI = f"AI (Human-like){INTERNAL_MARKER}"
OLD = f"\nMove 3: B A5\nOld text\nMove was automatically undone in teaching mode.\n{INTERNAL_MARKER}"
# Black (the user) plays C3, then A5 losing 8 points; the move has the user's note and KaTrain's old text.
GAME = f"(;SZ[5]KM[0.5]PB[{HUMAN}]PW[{AI}]C[game note];B[cc];W[bb];B[aa]C[my note{SEPARATOR}{OLD}])"
SCORES = {0: 0.0, 1: 1.0, 2: 3.0, 3: -5.0}  # White loses 2 points, black then 8.


class FakeEngine:
    """Answers at once, with a score that depends on the number of moves."""

    def query(self, request, callback):
        allowed = request.get("allowMoves")
        point = allowed[0]["moves"][0] if allowed else "E5"
        score = SCORES.get(len(request["moves"]) + (1 if allowed else 0), SCORES[3])  # Longer: KentoGo's readings.
        best = {"move": point, "order": 0, "visits": 9, "scoreLead": score, "winrate": 0.5, "pv": [point]}
        root = {"scoreLead": score, "winrate": 0.4 if score < 0 else 0.6, "visits": 9}
        callback({"id": "q", "rootInfo": root, "moveInfos": [best], "policy": [0.04] * 26, "ownership": [0.1] * 25})
        return "q"


def analyzed(settings: AnalysisSettings = AnalysisSettings()) -> object:
    root = GoGame.parse_sgf(GAME)
    game = analyze_game(FakeEngine(), root, settings, EngineValues(100, 0.0), lambda *_: None)
    write_analysis(game, WriteSettings(settings, "1.2.3"))
    return GoGame.parse_sgf(root.sgf())  # Written and read back.


def test_root_properties_and_comment():
    root = analyzed()
    assert (root.get_property("AP"), root.get_property("CA"), root.get_property("KTV")) == (
        "KentoGo:1.2.3",
        "UTF-8",
        "1.0",
    )
    assert root.get_property("C") == f"game note\n{SEPARATOR}\nSGF generated by KentoGo 1.2.3{INTERNAL_MARKER}"


def test_every_node_gets_analysis_data():
    root = analyzed()
    for node in root.nodes_in_tree:
        assert decode_kt(node.get_list_property("KT"))["completed"] is True


def test_comment_with_notes_and_the_teaching_undo_kept():
    """The note stays at the top; KaTrain's old text is replaced; the taken-back lines are kept."""
    mistake = analyzed().nodes_in_tree[3]
    notes, info = read_comment(mistake.get_property("C"))
    assert notes == "my note"
    assert (info.points_lost, info.best_move, info.teaching_undo) == (8.0, "E5", True)
    assert "Old text" not in mistake.get_property("C")


def test_comments_only_for_the_chosen_classes():
    """With KaTrain's defaults, a move that gained gets no comment (and a node without notes no C)."""
    nodes = analyzed().nodes_in_tree
    assert nodes[1].get_property("C") is None  # Black gained.
    assert read_comment(nodes[2].get_property("C"))[1].points_lost == 2.0  # The AI's move too.


def test_ai_moves_without_comments_when_eval_show_ai_is_off():
    settings = AnalysisSettings(eval_show_ai=False)
    nodes = analyzed(settings).nodes_in_tree
    assert nodes[2].get_property("C") is None  # White is KaTrain's AI.
    assert read_comment(nodes[3].get_property("C"))[1].points_lost == 8.0


def test_marks_and_start_message():
    root = analyzed(AnalysisSettings(save_marks=True))
    mistake = root.nodes_in_tree[3]
    assert mistake.get_property("MA") == "ea"
    start = "Moves marked 'X' indicate the top move according to KataGo"
    assert root.get_property("C").count(start) == 1  # Once (KaTrain writes it twice).


def test_kentogo_makes_a_problem_from_the_written_game():
    """The written game is read by KentoGo's own problem maker, from the analysis data."""
    result = extract_problems(analyzed(), "game.sgf", ExtractSettings())
    assert [(problem.move_number, problem.points_lost) for problem in result.problems] == [(3, 8.0)]


def test_backup_then_write(tmp_path):
    game = tmp_path / "game.sgf"
    game.write_bytes("(;C[元の棋譜])".encode("gb18030"))
    folder = backup_folder(tmp_path, "")
    copy = back_up(game, folder, datetime(2026, 11, 6, 17, 5, 9))
    assert copy == tmp_path / "backup" / "game 2026-11-06 170509.sgf"
    assert copy.read_bytes() == "(;C[元の棋譜])".encode("gb18030")  # Byte for byte.
    write_game(game, "(;C[新しい])")
    assert game.read_text(encoding="utf-8") == "(;C[新しい])"
    assert sorted(path.name for path in tmp_path.iterdir()) == ["backup", "game.sgf"]  # No file left behind.
    assert backup_folder(tmp_path, "~/other").name == "other"


def test_the_root_is_marked_as_analyzed_by_kentogo():
    """KGM[KentoGo] tells that the losses are read in the position before each move."""
    assert analyzed().get_property("KGM") == "KentoGo"


def test_kentogo_data_only_for_the_moves_read_deeply():
    """Black's A5 lost 8 points and is read deeply: it gets KGD; an old KGD of another node is removed."""
    root = GoGame.parse_sgf(GAME)
    write_kgd(root.nodes_in_tree[1], {"old": True})
    settings = AnalysisSettings()
    targets = DeepTargets({"B": 5.0, "W": 5.0}, 400)
    game = analyze_game(FakeEngine(), root, settings, EngineValues(100, 0.0), lambda *_: None, targets)
    write_analysis(game, WriteSettings(settings, "1.2.3"))
    nodes = GoGame.parse_sgf(root.sgf()).nodes_in_tree
    assert [read_kgd(node) is not None for node in nodes] == [False, False, False, True]
    data = read_kgd(nodes[3])
    assert (data["kind"], data["visits"], data["base"]) == ("move", 400, {"scoreLead": 3.0, "visits": 9})
    assert (data["played"]["move"], data["played"]["scoreLead"]) == ("A5", -5.0)
    assert (data["best"]["move"], data["best"]["scoreLead"]) == ("E5", 3.0)


def test_kentogo_data_has_the_readings():
    root = GoGame.parse_sgf(GAME)
    settings = AnalysisSettings()
    game = analyze_game(
        FakeEngine(), root, settings, EngineValues(100, 0.0), lambda *_: None, DeepTargets({"B": 5.0}, 400)
    )
    write_analysis(game, WriteSettings(settings, "1.2.3"))
    data = read_kgd(GoGame.parse_sgf(root.sgf()).nodes_in_tree[3])
    assert data["played_after"]["scoreLead"] == -5.0
    assert {"pass_before", "pass_after_played", "best_after", "pass_after_best"} <= set(data)
    assert len(data["best_after"]["ownership"].values) == 25  # Kept as a grid.


def test_positions_that_cannot_become_problems_keep_only_what_is_used():
    """KataGo's other values, the candidates read little, and the late candidates' sequences are left out."""
    many = {"move": "C3", "order": 0, "visits": 900, "scoreLead": 1.0, "winrate": 0.6, "prior": 0.3, "pv": ["C3", "D4"]}
    many |= {"utility": 0.1, "scoreSelfplay": 1.2, "humanPrior": 0.2, "lcb": 0.5}
    analysis = {
        "root": {"visits": 1000, "scoreLead": 1.0, "humanWinrate": 0.55},
        "moves": {
            "C3": many,
            "D4": {"move": "D4", "order": 7, "visits": 50, "scoreLead": 0.0, "pv": ["D4"]},
            "E5": {"move": "E5", "order": 8, "visits": 5, "scoreLead": -1.0, "pv": ["E5"]},  # Below 1 %.
            "A1": {"move": "A1", "order": 999, "visits": 1, "scoreLead": -9.0, "pv": ["A1", "B2"]},  # Played.
        },
        "ownership": [0.5] * 25,
        "policy": [0.04] * 26,
        "completed": True,
    }
    kept = kept_analysis(analysis, {"A1"})
    assert set(kept["moves"]) == {"C3", "D4", "A1"}
    assert set(kept["moves"]["C3"]) == {"move", "order", "visits", "scoreLead", "winrate", "prior", "pv"}
    assert "pv" not in kept["moves"]["D4"] and kept["moves"]["A1"]["pv"] == ["A1", "B2"]
    assert kept["root"] == analysis["root"] and kept["ownership"] == analysis["ownership"]  # KaTrain shows them.
    assert "utility" in analysis["moves"]["C3"]  # The analysis itself is not changed.


def test_problem_positions_keep_everything():
    """The move read deeply and the position before it keep all of KataGo's values; the others only the used ones."""

    class WithMore(FakeEngine):
        def query(self, request, callback):
            return super().query(request, lambda answer: callback(_with_utility(answer)))

    root = GoGame.parse_sgf(GAME)
    settings = AnalysisSettings()
    game = analyze_game(
        WithMore(), root, settings, EngineValues(100, 0.0), lambda *_: None, DeepTargets({"B": 5.0}, 400)
    )
    write_analysis(game, WriteSettings(settings, "1.2.3"))
    nodes = GoGame.parse_sgf(root.sgf()).nodes_in_tree
    has_utility = ["utility" in next(iter(decode_kt(node.get_list_property("KT"))["moves"].values())) for node in nodes]
    assert has_utility == [False, False, True, True]  # Move 3 (A5) and the position before it.


def _with_utility(answer):
    return {**answer, "moveInfos": [{**info, "utility": 0.1} for info in answer.get("moveInfos", [])]}
