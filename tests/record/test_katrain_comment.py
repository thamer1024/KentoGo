"""Tests for kentogo.record.katrain_comment."""

import re

import pytest

from kentogo.record.katrain_comment import (
    INTERNAL_MARKER,
    SEPARATOR,
    parse_katrain_text,
    parse_pv,
    read_comment,
    split_comment,
    template_to_regex,
)
from kentogo.record.katrain_texts import KATRAIN_TEXTS

GENERATED = "\nMove 3: B Q4\nScore: B+0.5\nEstimated point loss: 1.2\n" + INTERNAL_MARKER


def test_only_generated_text():
    """A comment with only KaTrain's text has no notes."""
    notes, generated = split_comment(GENERATED)
    assert notes == ""
    assert generated == ["Move 3: B Q4\nScore: B+0.5\nEstimated point loss: 1.2"]


def test_notes_and_generated_text():
    """Notes before the separator are kept apart from KaTrain's text."""
    comment = "My note\nsecond line\n" + SEPARATOR + GENERATED
    notes, generated = split_comment(comment)
    assert notes == "My note\nsecond line"
    assert len(generated) == 1


def test_only_notes():
    """A comment written only by the user is all notes."""
    notes, generated = split_comment("Just a note")
    assert notes == "Just a note"
    assert generated == []


def test_empty_comment():
    """An empty comment gives empty results."""
    assert split_comment("") == ("", [])


# Real texts from KaTrain 1.20.0 (the marker at the end is already removed by split_comment).
JAPANESE_MISTAKE = (
    "手数169: B H1\n目差：白+1.2\n勝率：白 96.0%\n推定損失目数：7.5\n最善手はQ14 (黒+6.4)\n"
    "予想手順：BQ14 M16 N15 M17 M18 R17 P17 A10 A9 A11 B9 T9 T8 S12\n"
    "第一感では14位  (0.00%)\n第一感での最有力手はQ14 (90.2%)"
)
JAPANESE_BEST = "手数1: B Q16\n目差：黒+0.2\n勝率：黒 66.7%\n最善手\n予想手順：BQ16 D6 D4 F4 C16 Q4 O3 L4"
JAPANESE_TEACHING_UNDO = (
    "手数38: B B1\n目差：黒+39.2\n勝率：黒 100.0%\n推定損失目数：12.3\n最善手はN4 (黒+52.0)\n"
    "予想手順：BN4 F16 G16 E17 F15 E16 J16 G15\n第一感では318位  (0.01%)\n第一感での最有力手はN4 (36.2%)\n"
    "指導モードにより自動的に待ったがかかりました\n予想手順：WF16 E16 E15 E17 O4 N4 O5 M4 M3"
)
ENGLISH_MISTAKE = (
    "Move 2: B Q4\nScore: B+13.0\nWin rate: B 65.2%\nEstimated point loss: 5.9\n"
    "Predicted top move was F17 (B+20.0).\nPV: BF17 C6 C14 D14 C17 C15 D17 C13 B14\n"
    "Move was #1 according to policy  (56.63%)."
)


def test_parse_japanese_mistake():
    """A Japanese text with a point loss gives the loss, best move and sequence."""
    info = parse_katrain_text(JAPANESE_MISTAKE)
    assert info.language == "jp"
    assert (info.move_number, info.color, info.move) == (169, "B", "H1")
    assert info.points_lost == 7.5
    assert info.best_move == "Q14"
    assert info.pv_color == "B"
    assert info.pv[:3] == ("Q14", "M16", "N15")
    assert info.teaching_undo is False


def test_parse_japanese_best_move():
    """When the played move was the best, the best move is the played move and there is no loss."""
    info = parse_katrain_text(JAPANESE_BEST)
    assert info.points_lost is None
    assert info.best_move == "Q16"
    assert info.pv[0] == "Q16"


def test_parse_teaching_undo():
    """In a teaching game, the sequence after the undo message is not read."""
    info = parse_katrain_text(JAPANESE_TEACHING_UNDO)
    assert info.teaching_undo is True
    assert info.pv_color == "B"
    assert info.pv[0] == "N4"


def test_parse_english_mistake():
    """The same values are read from an English text."""
    info = parse_katrain_text(ENGLISH_MISTAKE)
    assert info.language == "en"
    assert (info.move_number, info.move, info.points_lost, info.best_move) == (2, "Q4", 5.9, "F17")
    assert info.pv[:2] == ("F17", "C6")


def test_parse_text_that_is_not_about_a_move():
    """The comment on the first node is not about a move."""
    assert parse_katrain_text("SGF generated by KaTrain 1.20.0") is None


def test_parse_pv():
    """A sequence gives the color of the first move and the list of moves."""
    assert parse_pv("WD6 D4 pass") == ("W", ("D6", "D4", "pass"))
    assert parse_pv("") == (None, ())


def make_text(texts: dict[str, str], teaching_undo: bool = False) -> str:
    """Make a generated text in the same way as KaTrain's GameNode.comment(sgf=True).

    Args:
        texts: The KaTrain texts of one language.
        teaching_undo: Add the lines that KaTrain writes for an automatic undo.

    Returns:
        The text for move 169, black H1, with a loss of 7.5 points.
    """
    text = texts["move"].format(number=169) + ": B H1\n"
    text += "Score: W+1.2\n"  # Lines that KentoGo does not read.
    text += texts["Info:point loss"].format(points_lost=7.5) + "\n"
    text += texts["Info:top move"].format(top_move="Q14", score="B+6.4") + "\n"
    text += texts["Info:PV"].format(pv="BQ14 M16 N15") + "\n"
    if teaching_undo:
        text += texts["Info:teaching undo"] + "\n"
        text += texts["Info:undo predicted PV"].format(pv="WF16 E16") + "\n"
    return text


@pytest.mark.parametrize("language", sorted(KATRAIN_TEXTS))
def test_parse_all_languages(language):
    """A text made with the texts of each language is read correctly, and its language is found."""
    info = parse_katrain_text(make_text(KATRAIN_TEXTS[language]))
    assert info.language == language
    assert (info.move_number, info.color, info.move) == (169, "B", "H1")
    assert (info.points_lost, info.best_move) == (7.5, "Q14")
    assert (info.pv_color, info.pv) == ("B", ("Q14", "M16", "N15"))
    assert info.teaching_undo is False


def test_first_lines_differ_between_languages():
    """The first line of each language matches only that language.

    parse_katrain_text finds the language from the first line, so this must be true.
    If a new KaTrain version breaks it, the language must be found in another way.
    """
    for language, texts in KATRAIN_TEXTS.items():
        first_line = texts["move"].format(number=169) + ": B H1"
        found = [
            other
            for other, other_texts in KATRAIN_TEXTS.items()
            if re.fullmatch(template_to_regex(other_texts["move"]), first_line.split(":")[0])
        ]
        assert found == [language]


@pytest.mark.parametrize("language", sorted(KATRAIN_TEXTS))
def test_parse_teaching_undo_all_languages(language):
    """In every language, the sequence after the undo message is not read."""
    info = parse_katrain_text(make_text(KATRAIN_TEXTS[language], teaching_undo=True))
    assert info.teaching_undo is True
    assert info.pv[0] == "Q14"


@pytest.mark.parametrize("language", sorted(KATRAIN_TEXTS))
def test_parse_best_move_all_languages(language):
    """In every language, the "best move" line makes the played move the best move."""
    texts = KATRAIN_TEXTS[language]
    text = texts["move"].format(number=1) + ": B Q16\n" + texts["Info:best move"] + "\n"
    info = parse_katrain_text(text)
    assert info.best_move == "Q16"
    assert info.points_lost is None


def test_template_with_spaces_at_the_end():
    """Spaces at the end of a template do not break the regular expression."""
    assert re.fullmatch(template_to_regex("Move {number}  "), "Move 12")


def test_value_followed_by_letters():
    """A value can be followed directly by letters, as in Korean."""
    regex = template_to_regex(KATRAIN_TEXTS["ko"]["Info:top move"])
    match = re.fullmatch(regex, "예상한 최선의 수는 Q14입니다(흑+6.4).")
    assert match["top_move"] == "Q14"


def test_read_comment_with_notes():
    """A comment with notes and KaTrain's text gives both."""
    comment = "Claude's explanation\n" + SEPARATOR + "\n" + JAPANESE_MISTAKE + "\n" + INTERNAL_MARKER
    notes, info = read_comment(comment)
    assert notes == "Claude's explanation"
    assert info.move == "H1"


def test_read_comment_without_evaluation():
    """A comment without KaTrain's evaluation gives None for the evaluation."""
    assert read_comment("Just a note") == ("Just a note", None)
    assert read_comment("\nSGF generated by KaTrain 1.20.0" + INTERNAL_MARKER) == ("", None)
