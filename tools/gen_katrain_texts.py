"""Make the table of KaTrain texts that KentoGo uses to read SGF comments.

KaTrain writes its comments in the language that the user selected.
To read them in any language, KentoGo needs the same texts that KaTrain uses.
This script gets the texts in the same way as KaTrain does: it reads the
compiled translation files (.mo files) with Python's gettext, and uses the
default language (English) when a text is not translated. Then it writes
the texts as a Python module.

Usage:
    python tools/gen_katrain_texts.py KATRAIN_SOURCE_DIR OUTPUT_FILE

Example:
    python tools/gen_katrain_texts.py ../vendor/katrain src/kentogo/record/katrain_texts.py

Run this again when a new KaTrain version changes its texts.
"""

from __future__ import annotations

import argparse
import gettext
import json
import re
from pathlib import Path

# The message IDs in KaTrain's translation files that KentoGo needs.
KEYS = [
    "player:human",
    "player:ai",
    "game:normal",
    "game:teach",
    "move",
    "Info:point loss",
    "Info:PV",
    "Info:best move",
    "Info:top move",
    "Info:teaching undo",
    "Info:undo predicted PV",
]

HEADER = '''"""KaTrain texts for each language, used to read KaTrain's SGF comments.

This file is generated by tools/gen_katrain_texts.py. Do not edit it by hand.
Source: KaTrain {version}
"""
'''


def read_language(locales: Path, language: str, default_language: str) -> dict[str, str]:
    """Get the texts for KEYS in one language, in the same way as KaTrain.

    Args:
        locales: The folder that has one subfolder for each language.
        language: Language code, such as "jp".
        default_language: The language that KaTrain uses when a text is not translated.

    Returns:
        A dict from message ID to text.
    """
    translation = gettext.translation("katrain", locales, languages=[language, default_language])
    return {key: translation.gettext(key) for key in KEYS}


def read_default_language(katrain_dir: Path) -> str:
    """Read the default language of KaTrain from its source code.

    Args:
        katrain_dir: Top folder of the KaTrain source code.

    Returns:
        The language code, or "en" if it is not found.
    """
    lang_file = katrain_dir / "katrain" / "core" / "lang.py"
    match = re.search(r'^DEFAULT_LANGUAGE = "(.*)"', lang_file.read_text(encoding="utf-8"), re.MULTILINE)
    return match.group(1) if match else "en"


def read_katrain_version(katrain_dir: Path) -> str:
    """Read the KaTrain version from its constants file.

    Args:
        katrain_dir: Top folder of the KaTrain source code.

    Returns:
        The version string, or "unknown" if it is not found.
    """
    constants = katrain_dir / "katrain" / "core" / "constants.py"
    match = re.search(r'^VERSION = "(.*)"', constants.read_text(encoding="utf-8"), re.MULTILINE)
    return match.group(1) if match else "unknown"


def quote(text: str) -> str:
    """Write a string as a Python literal with double quotes, keeping non-ASCII letters as they are."""
    return json.dumps(text, ensure_ascii=False)


def build_module(table: dict[str, dict[str, str]], version: str) -> str:
    """Make the Python source code of the table module.

    Args:
        table: A dict from language code to the dict of texts.
        version: KaTrain version, written in the header.

    Returns:
        The source code as a string.
    """
    lines = [HEADER.format(version=version), "KATRAIN_TEXTS: dict[str, dict[str, str]] = {"]
    for language, texts in sorted(table.items()):
        lines.append(f"    {quote(language)}: {{")
        for key in KEYS:
            lines.append(f"        {quote(key)}: {quote(texts[key])},")
        lines.append("    },")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main() -> None:
    """Read the arguments, build the table, and write the output file."""
    parser = argparse.ArgumentParser(description="Make the table of KaTrain texts.")
    parser.add_argument("katrain_dir", type=Path, help="top folder of the KaTrain source code")
    parser.add_argument("output", type=Path, help="Python file to write")
    args = parser.parse_args()

    locales = args.katrain_dir / "katrain" / "i18n" / "locales"
    default_language = read_default_language(args.katrain_dir)
    table = {
        folder.name: read_language(locales, folder.name, default_language)
        for folder in locales.iterdir()
        if folder.is_dir()
    }
    args.output.write_text(build_module(table, read_katrain_version(args.katrain_dir)), encoding="utf-8")


if __name__ == "__main__":
    main()
